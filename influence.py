"""Robustness check: is the headline gap driven by one outlier language or name?

The pooled result says African names carry a higher CER than English ones. Two
fair objections attack its *stability* rather than any confound:

  1. **One language.** Maybe a single African language (say Hausa) is an outlier
     and the pooled gap collapses once it is removed.
  2. **A few names.** Maybe a handful of pathological names (one that Whisper
     mangles completely) carry the whole effect.

This script answers both with leave-one-out recomputation on a scored run
(default the clean-baseline gTTS isolated run):

  - **Leave-one-language-out (LOLO):** drop each African language in turn and
    recompute the pooled English-vs-African Cliff's delta, median gap and p.
  - **Leave-one-name-out (jackknife):** drop each name in turn and recompute
    Cliff's delta; report the full range and the single most influential name.

    python influence.py            # writes docs/influence.md + prints

Reproducible from the committed score tables — no TTS/ASR stack required.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from statistics import median

from ttsbench.stats import cers_by_language, cliffs_delta, english_vs_african


def load(run_dir: Path) -> list[dict]:
    """Scored rows: id, language, cer."""
    rows = []
    for r in csv.DictReader(open(run_dir / "scores.csv", encoding="utf-8")):
        rows.append({"id": r["id"], "language": r["language"],
                     "cer": float(r["cer"])})
    return rows


def _pooled(rows: list[dict]) -> dict | None:
    """Headline pooled result + the median gap (African − English)."""
    res = english_vs_african(rows)
    if res is None:
        return None
    res["median_gap"] = res["african_median"] - res["english_median"]
    return res


def leave_one_language_out(rows: list[dict]) -> list[dict]:
    """Drop each African language in turn; recompute the pooled headline."""
    langs = sorted(l for l in cers_by_language(rows) if l != "english")
    out = []
    for dropped in langs:
        kept = [r for r in rows if r["language"] != dropped]
        res = _pooled(kept)
        if res is None:
            continue
        out.append({"dropped": dropped, "p": res["p"],
                    "cliffs_delta": res["cliffs_delta"], "effect": res["effect"],
                    "median_gap": res["median_gap"],
                    "african_n": res["african_n"]})
    return out


def leave_one_name_out(rows: list[dict]) -> dict:
    """Jackknife Cliff's delta over single-name removals.

    Returns the full delta range and the name whose removal moves delta most
    (the most influential observation).
    """
    by = cers_by_language(rows)
    eng = by.get("english", [])
    afr_rows = [r for r in rows if r["language"] != "english"]
    base = cliffs_delta([r["cer"] for r in afr_rows], eng)

    deltas = []
    for drop in rows:
        if drop["language"] == "english":
            kept_eng = [c for r in rows
                        if r["language"] == "english" and r["id"] != drop["id"]
                        for c in [r["cer"]]]
            kept_afr = [r["cer"] for r in afr_rows]
        else:
            kept_eng = eng
            kept_afr = [r["cer"] for r in afr_rows if r["id"] != drop["id"]]
        d = cliffs_delta(kept_afr, kept_eng)
        deltas.append({"id": drop["id"], "language": drop["language"], "delta": d})

    most = max(deltas, key=lambda x: abs(x["delta"] - base))
    return {"base": base,
            "min": min(d["delta"] for d in deltas),
            "max": max(d["delta"] for d in deltas),
            "most_influential": most,
            "swing": abs(most["delta"] - base), "n": len(deltas)}


def report(rows: list[dict]) -> str:
    base = _pooled(rows)
    lolo = leave_one_language_out(rows)
    jack = leave_one_name_out(rows)

    lolo_stable = all(r["p"] < 0.05 and r["cliffs_delta"] > 0 for r in lolo)
    jack_stable = jack["min"] > 0 and jack["swing"] < 0.1

    lines = [
        "# Robustness: is the gap driven by one outlier language or name?",
        "",
        "Generated by `influence.py` from the committed scores "
        "(gTTS isolated, the clean-baseline run). Positive Cliff's delta = "
        "African names carry higher CER than English.",
        "",
        f"**Full sample.** Cliff's delta = {base['cliffs_delta']:+.3f} "
        f"({base['effect']}), median gap = {base['median_gap']:+.3f} CER, "
        f"Mann-Whitney p = {base['p']:.2e} "
        f"(English n = {base['english_n']}, African n = {base['african_n']}).",
        "",
        "**1. Leave-one-language-out.** Drop each African language, recompute the "
        "pooled English-vs-African result:",
        "",
        "| Dropped | African n | Cliff's delta | Effect | Median gap | p |",
        "|---|---|---|---|---|---|",
    ]
    for r in lolo:
        lines.append(
            f"| {r['dropped']} | {r['african_n']} | {r['cliffs_delta']:+.3f} | "
            f"{r['effect']} | {r['median_gap']:+.3f} | {r['p']:.2e} |")
    mi = jack["most_influential"]
    lines += [
        "",
        f"The gap stays positive and significant whichever single language is "
        f"removed — {'no one language drives it' if lolo_stable else 'but see the row(s) where it weakens'}.",
        "",
        "**2. Leave-one-name-out (jackknife).** Drop each of the "
        f"{jack['n']} names in turn and recompute Cliff's delta:",
        "",
        f"- Full-sample delta: {jack['base']:+.3f}.",
        f"- Range across all single-name removals: "
        f"[{jack['min']:+.3f}, {jack['max']:+.3f}].",
        f"- Most influential name: `{mi['id']}` ({mi['language']}) — "
        f"removing it moves delta to {mi['delta']:+.3f} "
        f"(swing {jack['swing']:.3f}).",
        "",
        f"No single name flips or collapses the effect "
        f"({'the delta range stays well above zero' if jack_stable else 'see the range above'}).",
        "",
        "**Conclusion.** "
        + ("The disparity is a property of the sample as a whole: it survives "
           "removing any one African language and no single name carries it. The "
           "headline is not an artefact of one outlier."
           if (lolo_stable and jack_stable) else
           "See the numbers above; the effect's stability is not fully "
           "established on this run."),
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", default="outputs")
    ap.add_argument("--out", default="docs/influence.md")
    args = ap.parse_args()

    rows = load(Path(args.run))
    if not rows:
        print(f"No scored rows in {args.run}. Run the pipeline first.")
        return
    text = report(rows)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n", encoding="utf-8")
    print(text)
    print(f"Written to {out}")


if __name__ == "__main__":
    main()
