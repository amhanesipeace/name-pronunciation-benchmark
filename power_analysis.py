"""How small a sample could still detect this gap? — a subsampling power curve.

The dataset's headline limitation is its size (20 names/language). But "small n"
conflates two separate things:

  - **Statistical power** — given the effect, how reliably does a test of this
    size reject the null? That is what this script measures.
  - **Representativeness** — do 20 names stand in for a language's full name
    space? That is a sampling-frame question no amount of power addresses, and
    it remains the real limitation (see README ethics / DATASHEET).

This separates the two. It repeatedly draws *smaller* subsamples from the
committed scores (gTTS isolated, the clean-baseline run), re-runs the one-sided
Mann-Whitney test, and reports the fraction that stay significant — the
empirical detection rate (power) at each per-group n, treating the observed
sample as the population.

    python power_analysis.py            # writes docs/power_analysis.md + prints

This is a subsampling sensitivity, NOT an a-priori power calculation: it assumes
the observed effect is the true effect, so read it as "would a smaller study
have caught a gap this size?", not as a guarantee about an unseen population.

Reproducible (seeded) from the committed score tables — no TTS/ASR stack.
"""
from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path
from statistics import median

from scipy.stats import mannwhitneyu

from ttsbench.stats import cers_by_language, cliffs_delta

NS = [5, 8, 10, 12, 15, 20]
ALPHA = 0.05
DEFAULT_ITERS = 1000


def load(run_dir: Path) -> list[dict]:
    rows = []
    for r in csv.DictReader(open(run_dir / "scores.csv", encoding="utf-8")):
        rows.append({"language": r["language"], "cer": float(r["cer"])})
    return rows


def _split(rows: list[dict]) -> tuple[list[float], list[float]]:
    by = cers_by_language(rows)
    eng = by.get("english", [])
    afr = [c for lang, cers in by.items() if lang != "english" for c in cers]
    return eng, afr


def subsample_power(eng: list[float], afr: list[float], n: int, *,
                    iters: int, rng: random.Random) -> dict:
    """Detection rate when each group is subsampled (without replacement) to n.

    Returns the fraction of draws where the one-sided Mann-Whitney test is
    significant at ALPHA, plus the median Cliff's delta across draws.
    """
    n_eng, n_afr = min(n, len(eng)), min(n, len(afr))
    hits, deltas = 0, []
    for _ in range(iters):
        se = rng.sample(eng, n_eng)
        sa = rng.sample(afr, n_afr)
        try:
            _, p = mannwhitneyu(sa, se, alternative="greater")
        except ValueError:          # degenerate draw (all values identical)
            p = 1.0
        if p < ALPHA:
            hits += 1
        deltas.append(cliffs_delta(sa, se))
    return {"n": n, "n_eng": n_eng, "n_afr": n_afr,
            "power": hits / iters if iters else float("nan"),
            "median_delta": median(deltas) if deltas else float("nan")}


def power_curve(rows: list[dict], *, ns=NS, iters: int = DEFAULT_ITERS,
                seed: int = 0) -> list[dict]:
    eng, afr = _split(rows)
    rng = random.Random(seed)
    return [subsample_power(eng, afr, n, iters=iters, rng=rng) for n in ns]


def smallest_n_for_power(curve: list[dict], target: float = 0.80) -> int | None:
    """Smallest per-group n whose detection rate meets the target, or None."""
    for row in sorted(curve, key=lambda r: r["n"]):
        if row["power"] >= target:
            return row["n"]
    return None


def report(rows: list[dict], *, iters: int = DEFAULT_ITERS) -> str:
    curve = power_curve(rows, iters=iters)
    n80 = smallest_n_for_power(curve, 0.80)
    full = curve[-1]
    lines = [
        "# How small a sample could still detect the gap?",
        "",
        "Generated by `power_analysis.py` from the committed scores (gTTS "
        f"isolated, the clean-baseline run), {iters} subsamples per row, seeded. "
        "Each row draws that many names *per group* (English / African) without "
        "replacement and re-runs the one-sided Mann-Whitney test; **power** is the "
        "fraction that stay significant at p < 0.05.",
        "",
        "| Names per group | Power (detection rate) | Median Cliff's delta |",
        "|---|---|---|",
    ]
    for r in curve:
        lines.append(f"| {r['n']} | {r['power']:.3f} | {r['median_delta']:+.3f} |")
    lines += [
        "",
        (f"- Smallest per-group sample with ≥80% power: **{n80} names**."
         if n80 is not None else
         "- No tested sample size reached 80% power."),
        f"- At {full['n']} names per group the test detects the gap essentially "
        f"every time (power {full['power']:.3f}).",
        "",
        "**Conclusion.** The disparity is large enough that even a handful of "
        "names per group detects it reliably, so the study is not "
        "*under-powered*. The 20-names-per-language limit is therefore about "
        "**representativeness** — whether these names stand in for each language's "
        "full name space — not statistical power. That sampling-frame question is "
        "the real limitation and is addressed separately (README ethics, "
        "`data/DATASHEET.md`), not here.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", default="outputs")
    ap.add_argument("--out", default="docs/power_analysis.md")
    ap.add_argument("--iters", type=int, default=DEFAULT_ITERS)
    args = ap.parse_args()

    rows = load(Path(args.run))
    if not rows:
        print(f"No scored rows in {args.run}. Run the pipeline first.")
        return
    text = report(rows, iters=args.iters)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n", encoding="utf-8")
    print(text)
    print(f"Written to {out}")


if __name__ == "__main__":
    main()
