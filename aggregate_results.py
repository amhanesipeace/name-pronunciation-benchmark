"""Aggregate every scored run into one master comparison table (RESULTS.md).

Scans `outputs*/` directories for a `manifest.csv` + `scores.csv`, derives the
engine and condition (isolated vs carrier) and dataset size, and reports
English vs African mean CER and the gap — so all runs sit side by side.

    python aggregate_results.py            # writes RESULTS.md + prints it
"""
import csv
import glob
from pathlib import Path
from statistics import mean

from ttsbench.stats import english_vs_african


def summarise(run_dir: Path) -> dict | None:
    scores_path = run_dir / "scores.csv"
    manifest_path = run_dir / "manifest.csv"
    if not scores_path.exists():
        return None

    scores = list(csv.DictReader(open(scores_path, encoding="utf-8")))
    if not scores:
        return None

    engine = scores[0].get("engine", "?")
    carrier = False
    if manifest_path.exists():
        man = list(csv.DictReader(open(manifest_path, encoding="utf-8")))
        carrier = any((r.get("carrier") or "").strip() for r in man)

    eng = [float(s["cer"]) for s in scores if s["language"] == "english"]
    afr = [float(s["cer"]) for s in scores if s["language"] != "english"]
    if not eng or not afr:
        return None

    stat = english_vs_african(scores)   # Mann-Whitney U + Cliff's delta
    return {
        "run": run_dir.name,
        "engine": engine,
        "condition": "carrier" if carrier else "isolated",
        "n": len(scores),
        "english_cer": mean(eng),
        "african_cer": mean(afr),
        "gap": mean(afr) - mean(eng),
        "delta": stat["cliffs_delta"] if stat else 0.0,
        "effect": stat["effect"] if stat else "-",
        "p": stat["p"] if stat else 1.0,
    }


def main():
    runs = sorted(Path(p).parent for p in glob.glob("outputs*/scores.csv"))
    rows = [r for r in (summarise(d) for d in runs) if r]
    # order: by engine, then isolated before carrier, then n
    rows.sort(key=lambda r: (r["engine"], r["condition"], r["n"]))

    lines = [
        "# Master results",
        "",
        "Every scored run, side by side. Lower CER = better; the **gap** "
        "(African − English mean CER) is the bias signal. Generated by "
        "`aggregate_results.py`.",
        "",
        "| engine | condition | n | English CER | African CER | gap | "
        "Cliff's δ | p |",
        "|--------|-----------|--:|------------:|------------:|----:|"
        "----------|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['engine']} | {r['condition']} | {r['n']} "
            f"| {r['english_cer']:.2f} | {r['african_cer']:.2f} "
            f"| **+{r['gap']:.2f}** | {r['delta']:+.2f} ({r['effect']}) "
            f"| {r['p']:.1e} |")
    lines += [
        "",
        "Notes: a *clean* English baseline (near 0) makes the gap interpretable; "
        "engines whose isolated audio the ASR can't read (espeak, MMS) saturate "
        "the metric — compare **within** an engine and prefer the carrier rows. "
        "See [FINDINGS.md](FINDINGS.md) for significance tests and discussion.",
    ]
    report = "\n".join(lines)
    Path("RESULTS.md").write_text(report + "\n", encoding="utf-8")
    print(report)
    print("\nWritten to RESULTS.md")


if __name__ == "__main__":
    main()
