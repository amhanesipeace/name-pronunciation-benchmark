"""Robustness check: is the bias just a name-length effect?

A fair objection to the headline gap: African names might simply be *longer*, and
longer strings might be harder to transcribe — so the disparity could be about
length, not origin. This script tests that confound on a scored run (default the
clean-baseline gTTS isolated run) and writes a short markdown report.

Three tests:
  1. Are African names actually longer? (Mann-Whitney U on character length.)
  2. Does per-name CER track length at all? (Spearman, within African and overall.)
  3. Does the English-vs-African gap survive at *matched* lengths? (restrict to
     the overlapping length band, then compare CER.)

    python length_confound.py            # writes docs/length_confound.md + prints

Reproducible from the committed score tables — no TTS/ASR stack required.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from statistics import mean, median

from scipy.stats import mannwhitneyu, spearmanr


def load(run_dir: Path, names_csv: Path) -> list[dict]:
    """Scored rows joined with each name's character length."""
    names = {r["id"]: r for r in csv.DictReader(open(names_csv, encoding="utf-8"))}
    rows = []
    for r in csv.DictReader(open(run_dir / "scores.csv", encoding="utf-8")):
        nm = names.get(r["id"])
        if not nm:
            continue
        rows.append({"id": r["id"], "language": r["language"],
                     "cer": float(r["cer"]), "len": len(nm["name"])})
    return rows


def split(rows: list[dict]) -> tuple[list[dict], list[dict]]:
    eng = [r for r in rows if r["language"] == "english"]
    afr = [r for r in rows if r["language"] != "english"]
    return eng, afr


def length_gap(rows: list[dict]) -> dict:
    """Are African names longer than English? (one-sided Mann-Whitney U)."""
    eng, afr = split(rows)
    u, p = mannwhitneyu([r["len"] for r in afr], [r["len"] for r in eng],
                        alternative="greater")
    return {"english_median_len": median([r["len"] for r in eng]),
            "african_median_len": median([r["len"] for r in afr]),
            "english_mean_len": mean([r["len"] for r in eng]),
            "african_mean_len": mean([r["len"] for r in afr]),
            "p": float(p)}


def cer_length_corr(rows: list[dict]) -> dict:
    """Spearman correlation of CER with length (needs variance in both)."""
    lens = [r["len"] for r in rows]
    cers = [r["cer"] for r in rows]
    if len(set(lens)) < 2 or len(set(cers)) < 2 or len(rows) < 3:
        return {"rho": float("nan"), "p": float("nan"), "n": len(rows)}
    res = spearmanr(lens, cers)
    return {"rho": float(res.correlation), "p": float(res.pvalue), "n": len(rows)}


def matched_gap(rows: list[dict]) -> dict:
    """English vs African CER restricted to the overlapping length band."""
    eng, afr = split(rows)
    lo = max(min(r["len"] for r in eng), min(r["len"] for r in afr))
    hi = min(max(r["len"] for r in eng), max(r["len"] for r in afr))
    eb = [r for r in eng if lo <= r["len"] <= hi]
    ab = [r for r in afr if lo <= r["len"] <= hi]
    out = {"lo": lo, "hi": hi, "english_n": len(eb), "african_n": len(ab),
           "english_cer": mean([r["cer"] for r in eb]) if eb else float("nan"),
           "african_cer": mean([r["cer"] for r in ab]) if ab else float("nan"),
           "p": float("nan")}
    if eb and ab:
        u, p = mannwhitneyu([r["cer"] for r in ab], [r["cer"] for r in eb],
                            alternative="greater")
        out["p"] = float(p)
    return out


def report(rows: list[dict]) -> str:
    lg = length_gap(rows)
    eng, afr = split(rows)
    corr_all = cer_length_corr(rows)
    corr_afr = cer_length_corr(afr)
    mg = matched_gap(rows)
    longer = lg["p"] < 0.05
    tracks = corr_all["p"] < 0.05 and abs(corr_all["rho"]) >= 0.3
    survives = mg["p"] < 0.05
    lines = [
        "# Robustness: is the bias just a name-length effect?",
        "",
        "Generated by `length_confound.py` from the committed scores "
        "(gTTS isolated, the clean-baseline run). Character length = letters in "
        "the name.",
        "",
        "**1. Are African names longer?**",
        "",
        f"- English: median {lg['english_median_len']:.1f}, "
        f"mean {lg['english_mean_len']:.2f} characters.",
        f"- African: median {lg['african_median_len']:.1f}, "
        f"mean {lg['african_mean_len']:.2f} characters.",
        f"- African > English length: Mann-Whitney U **p = {lg['p']:.2e}** "
        f"({'yes, slightly longer' if longer else 'no significant difference'}).",
        "",
        "**2. Does CER track length?**",
        "",
        f"- All names: Spearman ρ = {corr_all['rho']:+.3f} "
        f"(p = {corr_all['p']:.2e}, n = {corr_all['n']}).",
        f"- Within African names: ρ = {corr_afr['rho']:+.3f} "
        f"(p = {corr_afr['p']:.2e}, n = {corr_afr['n']}).",
        f"- Length {'predicts' if tracks else 'does **not** predict'} CER.",
        "",
        "**3. Does the gap survive at matched lengths?**",
        "",
        f"- Overlapping length band: {mg['lo']}–{mg['hi']} characters "
        f"(English n = {mg['english_n']}, African n = {mg['african_n']}).",
        f"- In-band mean CER: English {mg['english_cer']:.3f} vs "
        f"African {mg['african_cer']:.3f}.",
        f"- African > English CER in-band: **p = {mg['p']:.2e}** "
        f"({'gap persists' if survives else 'gap does not persist'}).",
        "",
        "**Conclusion.** "
        + ("African names are marginally longer, but length does not predict CER "
           "and the English–African gap persists at matched lengths — the "
           "disparity is driven by name origin/phonology, not string length."
           if (not tracks and survives) else
           "See the numbers above; the length confound is not ruled out on this "
           "run."),
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", default="outputs")
    ap.add_argument("--names", default="data/names.csv")
    ap.add_argument("--out", default="docs/length_confound.md")
    args = ap.parse_args()

    rows = load(Path(args.run), Path(args.names))
    if not rows:
        print(f"No scored rows in {args.run}. Run the pipeline first.")
        return
    text = report(rows)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n", encoding="utf-8")
    print(text)
    print(f"Written to {out}")


if __name__ == "__main__":
    main()
