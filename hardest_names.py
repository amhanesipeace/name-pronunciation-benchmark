"""Which names are hard across *independent* TTS systems — and which aren't.

`cross_engine.py` asks how correlated two engines' per-name difficulty is (one
number, Spearman rho). This is its concrete, per-name companion: it ranks the
names that are hard across several engines at once, and — just as importantly —
shows how much of the difficulty is engine-specific rather than intrinsic to the
name.

Why rank, not raw CER: espeak and isolated MMS *saturate* the ASR metric (their
English baselines are already poor), so their absolute CERs are not comparable to
gTTS's. Ranking each name **within its own engine** (as a percentile over all
names in that run) sidesteps the saturation and makes "hard for this system"
comparable across systems. A name's consensus difficulty is then its mean
within-engine percentile.

    python hardest_names.py              # writes docs/hardest_names.md + prints

Reproducible from the committed score tables for three independent engines
(gTTS, espeak-ng, Meta MMS) — no TTS/ASR stack required.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path
from statistics import mean

# Default: the three distinct engines at n=80, isolated-word condition.
DEFAULT_RUNS = {"gtts": "outputs", "espeak": "outputs_espeak", "mms": "outputs_mms"}
HARD = 0.67            # "hard" = top third within an engine (percentile >= this)


def load_run(run_dir: Path) -> list[dict]:
    rows = []
    for r in csv.DictReader(open(run_dir / "scores.csv", encoding="utf-8")):
        rows.append({"id": r["id"], "name": r["name"],
                     "language": r["language"], "cer": float(r["cer"])})
    return rows


def percentile_ranks(rows: list[dict]) -> dict[str, float]:
    """Each name's within-run difficulty as a percentile in [0, 1].

    Percentile = fraction of the other names in this run with a *lower* CER, so
    0 is the easiest name in the run and 1 the hardest. Ties (common when many
    names score 0) share the same value. Rank-based, so it is immune to a run's
    absolute-CER saturation.
    """
    n = len(rows)
    if n < 2:
        return {r["id"]: 0.0 for r in rows}
    cers = [r["cer"] for r in rows]
    out = {}
    for r in rows:
        lower = sum(1 for c in cers if c < r["cer"])
        out[r["id"]] = lower / (n - 1)
    return out


def consensus(runs: dict[str, list[dict]]) -> list[dict]:
    """Per-name mean within-engine percentile across the given runs.

    Returns African-language names only (English names are near-zero CER
    everywhere, so they carry no difficulty signal), sorted hardest-first. Each
    row carries the per-engine percentiles so engine-specific spikes are visible.
    """
    engines = list(runs)
    ranks = {e: percentile_ranks(runs[e]) for e in engines}
    meta = {r["id"]: r for e in engines for r in runs[e]}
    # Names present in every run (so the mean is over the same engine set).
    common = set.intersection(*[{r["id"] for r in runs[e]} for e in engines])
    rows = []
    for nid in common:
        if meta[nid]["language"] == "english":
            continue
        pcts = {e: ranks[e][nid] for e in engines}
        rows.append({"id": nid, "name": meta[nid]["name"],
                     "language": meta[nid]["language"],
                     "per_engine": pcts, "consensus": mean(pcts.values()),
                     "hard_in": sum(1 for v in pcts.values() if v >= HARD)})
    rows.sort(key=lambda r: r["consensus"], reverse=True)
    return rows


def summarise(runs: dict[str, list[dict]]) -> dict:
    engines = list(runs)
    ranks = {e: percentile_ranks(runs[e]) for e in engines}
    meta = {r["id"]: r for e in engines for r in runs[e]}
    common = set.intersection(*[{r["id"] for r in runs[e]} for e in engines])

    def mean_consensus(lang_pred) -> float:
        vals = [mean(ranks[e][nid] for e in engines)
                for nid in common if lang_pred(meta[nid]["language"])]
        return mean(vals) if vals else 0.0

    afr = consensus(runs)
    n_all = sum(1 for r in afr if r["hard_in"] == len(engines))
    n_two = sum(1 for r in afr if r["hard_in"] >= 2)
    return {
        "engines": engines,
        "english_mean": mean_consensus(lambda l: l == "english"),
        "african_mean": mean_consensus(lambda l: l != "english"),
        "n_african": len(afr),
        "hard_in_all": n_all,
        "hard_in_two_plus": n_two,
        "ranked": afr,
    }


def report(runs: dict[str, list[dict]], top: int = 10) -> str:
    s = summarise(runs)
    engines = s["engines"]
    head = "| Name | Language | Consensus | " + " | ".join(engines) + " |"
    sep = "| --- | --- | --: | " + " | ".join("--:" for _ in engines) + " |"
    lines = [
        "# Which names are hard across independent systems?",
        "",
        "Generated by `hardest_names.py` from the committed scores for three "
        f"independent engines ({', '.join(engines)}), isolated-word condition. "
        "Each name is ranked **within its own engine** as a percentile (0 = "
        "easiest name in that run, 1 = hardest), which is immune to the ASR-metric "
        "saturation that inflates espeak and isolated-MMS CERs. A name's consensus "
        "difficulty is its mean within-engine percentile.",
        "",
        f"**Across engines, African names rank harder than English ones:** mean "
        f"consensus percentile {s['african_mean']:.2f} vs {s['english_mean']:.2f}. "
        "The bias is not an artefact of a single system.",
        "",
        f"**But difficulty is only partly intrinsic to the name.** The top third "
        f"(percentile ≥ {HARD:g}) of *all {len(engines)}* engines contains "
        f"**{s['hard_in_all']}** of the {s['n_african']} African names, and at "
        f"least two engines' top third contains **{s['hard_in_two_plus']}** — so a "
        "sizeable group is broadly hard, yet most names that break one system are "
        "handled better by another. There is no single set of universally "
        "'unpronounceable' names; the bias is a population-level property "
        "(consistent with the moderate cross-engine rank correlation in "
        "`cross_engine.py`).",
        "",
        f"## Hardest {top} names by cross-engine consensus",
        "",
        head, sep,
    ]
    for r in s["ranked"][:top]:
        pe = " | ".join(f"{r['per_engine'][e]:.2f}" for e in engines)
        lines.append(f"| {r['name']} | {r['language']} | "
                     f"{r['consensus']:.2f} | {pe} |")
    lines += [
        "",
        "Percentiles near 1 in every column mark a name that every system finds "
        "hard; a high consensus built on one spiking column is an engine-specific "
        "failure. Both are visible row by row.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", nargs="+", default=None,
                    help="engine=dir pairs; default the three isolated runs")
    ap.add_argument("--top", type=int, default=10)
    ap.add_argument("--out", default="docs/hardest_names.md")
    args = ap.parse_args()

    spec = DEFAULT_RUNS
    if args.runs:
        spec = dict(pair.split("=", 1) for pair in args.runs)
    try:
        runs = {e: load_run(Path(d)) for e, d in spec.items()}
    except FileNotFoundError as exc:
        print(f"Missing scores for a run ({exc}). Score those engines first.")
        return
    text = report(runs, top=args.top)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n", encoding="utf-8")
    print(text)
    print(f"Written to {out}")


if __name__ == "__main__":
    main()
